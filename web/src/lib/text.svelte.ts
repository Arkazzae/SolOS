export type Lang = 'en' | 'pl';
export const LANGS: readonly Lang[] = ['en', 'pl'];
export const LANG_NAMES: Readonly<Record<Lang, string>> = { en: 'English', pl: 'Polski' };
export const isLang = (value: unknown): value is Lang => LANGS.includes(value as Lang);

/** A count with its noun: Polish one, few (2-4 but not 12-14) and many. */
function pl3(n: number, one: string, few: string, many: string): string {
  const tens = n % 100;
  const word = n === 1 ? one : n % 10 >= 2 && n % 10 <= 4 && (tens < 12 || tens > 14) ? few : many;
  return `${n} ${word}`;
}

/** The consoles with their games' extensions, as a sentence's list: "NES (.nes), … and PICO-8 (…)". */
function supported(lang: Lang): string {
  const items = SYSTEM_IDS.map((id) => `${SYSTEMS[id].name} (${SYSTEMS[id].extensions.map((ext) => `.${ext}`).join(', ')})`);
  return new Intl.ListFormat(lang, { type: 'conjunction' }).format(items);
}

/** A size in bytes, as KB, MB or GB, with the language's decimal mark. */
function bytes(lang: Lang, n: number): string {
  const one = (value: number, unit: string) => `${value.toLocaleString(lang, { maximumFractionDigits: 1 })} ${unit}`;
  if (n >= 1 << 30) return one(n / (1 << 30), 'GB');
  if (n >= 1 << 20) return one(n / (1 << 20), 'MB');
  return `${Math.max(1, Math.round(n / 1024))} KB`;
}

