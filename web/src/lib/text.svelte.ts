const TEXTS: Readonly<Record<Lang, Text>> = { en, pl };

let current = $state<Lang>('en');

/** The language the page speaks now. */
export function lang(): Lang {
  return current;
}

export function setLang(next: Lang): void {
  current = next;
  document.documentElement.lang = next;
}

/** The current language's words. */
export const t: Text = new Proxy(en, {
  get: (_, key) => TEXTS[current][key as keyof Text],
});
